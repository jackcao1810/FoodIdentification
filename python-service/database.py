    cursor = conn.cursor()
    cursor.execute('SELECT * FROM dishes WHERE food101_class = ?', (food101_class.lower(),))
    row = cursor.fetchone()
    conn.close()
    if row:
        columns = [desc[0] for desc in cursor.description]
        return dict(zip(columns, row))
    return None


